namespace
{
    /** The time for the removed part of an impulse to lose 60 dB of its energy (backward integration), in ms. */
    double ringingMs (SplitFilter& filter, float depth, double rate)
    {
        const auto n = impulseLength (rate);
        const auto h = impulseResponse (filter, depth, n);
        std::vector<double> tail ((size_t) n + 1, 0.0);
        for (auto i = (size_t) n; i-- > 0;)
        {
            const auto removed = (i == 0 ? 1.0 : 0.0) - h[i];
            tail[i] = tail[i + 1] + removed * removed;
        }
        for (size_t i = 0; i < (size_t) n; ++i)
            if (tail[i] < 1.0e-6 * tail[0])
                return 1000.0 * (double) i / rate;
        return 1000.0 * n / rate;
    }

}


    double relativeError (double a, double b) { return std::abs (a - b) / std::max (std::abs (b), 1.0e-300); }

    bool sameBits (double a, double b) { return std::memcmp (&a, &b, sizeof (double)) == 0; }

    struct Band
    {
        SplitKind kind;
        double low, high;
    };

    /** The Ess band the chain hands Split for these Detect handles: the detector's band, a shelf from 0.4 fs. */
    Band essBand (double detectLow, double detectHigh, double rate)
    {
        DetectorSettings s;
        s.detectLowHz = (float) detectLow;
        s.detectHighHz = (float) detectHigh;
        const auto b = Detector::bandsFor (s, rate);
        return { SplitFilter::kindFor (std::max (s.detectLowHz, s.detectHighHz), rate), b.essLow, b.essHigh };
    }

    Band harshBand (double freq, double widthOct, double rate)
    {
        DetectorSettings s;
        s.harshFreqHz = (float) freq;
        s.harshWidthOct = (float) widthOct;
        const auto b = Detector::bandsFor (s, rate);
        return { SplitKind::bell, b.harshLow, b.harshHigh };
    }

    const splitDesign::Prototype& prototypeOf (bool harsh) { return harsh ? splitDesign::harsh() : splitDesign::ess(); }

    /** A filter for one band, prepared at `rate`. */
    SplitFilter filterFor (const Band& b, double rate, bool harsh)
    {
        SplitFilter f (prototypeOf (harsh));
        f.prepare (rate);
        f.setBand (b.kind, b.low, b.high);
        f.reset();
        return f;
    }

    /** Long enough for the slowest pole (a third of an octave at 750 Hz) to decay under 1e-12. */
    int impulseLength (double rate) { return 16384 << std::max (0, (int) std::lround (std::log2 (rate / 44100.0))); }

    /** Runs a filter over `x` with depths per sample in chunks of `chunk`, as the chain hands them (each chunk's depths run on to its segment's end). */
    std::vector<double> runChunked (SplitFilter& f, const std::vector<double>& x, const std::vector<float>& depth, int chunk, int phase = 0)
    {
        std::vector<double> removed (x.size());
        std::vector<float> padded (depth);
        padded.resize (depth.size() + SplitFilter::interval, depth.back());
        for (size_t done = 0; done < x.size(); done += (size_t) chunk)
        {
            const auto n = (int) std::min ((size_t) chunk, x.size() - done);
            f.process (x.data() + done, padded.data() + done, removed.data() + done, n, phase + (int) done);
        }
        return removed;
    }

    /** The largest change a third of an octave or more past the band's edges, up to 0.45 fs (the collateral gate's reading), and where. */
    struct Outside
    {
        double db = 0.0, hz = 0.0, depthDb = 0.0;
        Band band { SplitKind::bell, 0.0, 0.0 };

        void take (double changeDb, double atHz, double atDepthDb, const Band& b)
        {
            if (std::abs (changeDb) > std::abs (db))
                *this = { changeDb, atHz, atDepthDb, b };
        }
    };

    struct Worst
    {
        double errorDb = 0.0, hz = 0.0, depthDb = 0.0;
        Band band { SplitKind::bell, 0.0, 0.0 };
        double tail = 0.0;          // the largest |h| in the last eighth of any impulse response
        int cases = 0;
        Outside outside, outsideTo16Db, outsideAnalog;      // measured at any depth and up to 16 dB, and the analog prototype

        void merge (const Worst& w)
        {
            if (std::abs (w.errorDb) > std::abs (errorDb))
            {
                errorDb = w.errorDb;
                hz = w.hz;
                depthDb = w.depthDb;
                band = w.band;
            }
            outside.take (w.outside.db, w.outside.hz, w.outside.depthDb, w.outside.band);
            outsideTo16Db.take (w.outsideTo16Db.db, w.outsideTo16Db.hz, w.outsideTo16Db.depthDb, w.outsideTo16Db.band);
            outsideAnalog.take (w.outsideAnalog.db, w.outsideAnalog.hz, w.outsideAnalog.depthDb, w.outsideAnalog.band);
            tail = std::max (tail, w.tail);
            cases += w.cases;
        }
    };

    /** The worst |measured − analog| in dB over 20 Hz … 0.45 fs (every FFT bin and 0.45 fs itself) for one band and depths. */
    Worst measureBand (const Band& b, double rate, bool harsh, const std::vector<double>& depthsDb, DoubleFft& fft)
    {
        Worst w;
        w.band = b;
        const auto& p = prototypeOf (harsh);
        auto filter = filterFor (b, rate, harsh);
        const auto n = impulseLength (rate);
        const auto top = 0.45 * rate;
        std::vector<Complex> spectrum ((size_t) n);

        for (const auto db : depthsDb)
        {
            const auto depth = depthFor (db);
            const auto h = impulseResponse (filter, depth, n);
            for (auto i = (size_t) (7 * n / 8); i < (size_t) n; ++i)
                w.tail = std::max (w.tail, std::abs (h[i]));

            for (size_t i = 0; i < (size_t) n; ++i)
                spectrum[i] = h[i];
            fft.transform (spectrum);

            const auto check = [&] (double hz, double measuredDb)
            {
                const auto analog = analogDb (p, b.kind, b.low, b.high, hz, gainOf (depth));
                const auto e = measuredDb - analog;
                if (std::abs (e) > std::abs (w.errorDb))
                {
                    w.errorDb = e;
                    w.hz = hz;
                    w.depthDb = db;
                }
                if (hz <= b.low / splitDesign::guard || (b.kind == SplitKind::bell && hz >= b.high * splitDesign::guard))
                {
                    w.outside.take (measuredDb, hz, db, b);
                    if (db <= 16.0)
                        w.outsideTo16Db.take (measuredDb, hz, db, b);
                    w.outsideAnalog.take (analog, hz, db, b);
                }
            };
            for (int k = 1; k <= n / 2; ++k)
                if (const auto hz = k * rate / n; hz >= 20.0 && hz <= top)
                    check (hz, 20.0 * std::log10 (std::abs (spectrum[(size_t) k])));
            check (top, responseDbAt (h, top, rate));
            ++w.cases;
        }
        return w;
    }

    const std::vector<double> essDepths { 0.25, 0.5, 1.0, 2.0, 3.0, 4.5, 6.0, 8.0, 10.0, 12.0, 15.0, 18.0, 21.0, 24.0 };
    const std::vector<double> harshDepths { 0.25, 0.5, 1.0, 2.0, 3.0, 4.0, 6.0, 8.0, 10.0, 12.0 };

    /** Every Ess band from Detect handles on a geometric grid over 1.5 … 20 kHz (each pair once, equal handles widened). */
    Worst essGrid (double rate, int stepsPerOctave, bool shelves)
    {
        std::vector<double> handles;
        for (auto hz = 1500.0; hz < 20000.0; hz *= std::exp2 (1.0 / stepsPerOctave))
            handles.push_back (hz);
        handles.push_back (20000.0);

        DoubleFft fft;
        Worst worst;
        for (size_t i = 0; i < handles.size(); ++i)
            for (size_t j = i; j < handles.size(); ++j)
                if (const auto b = essBand (handles[i], handles[j], rate); (b.kind == SplitKind::highShelf) == shelves)
                    worst.merge (measureBand (b, rate, false, essDepths, fft));
        return worst;
    }

    /** Every Harsh band on a grid of Freq (1.5 … 6 kHz, geometric) and Width (0.3 … 2 octaves). */
    Worst harshGrid (double rate, int stepsPerOctave)
    {
        DoubleFft fft;
        Worst worst;
        for (auto freq = 1500.0; freq <= 6000.0 * 1.0001; freq *= std::exp2 (1.0 / stepsPerOctave))
            for (auto width = 0.3; width <= 2.0001; width += 0.1 * 6 / stepsPerOctave)
                worst.merge (measureBand (harshBand (freq, width, rate), rate, true, harshDepths, fft));
        return worst;
    }

    void print (const char* what, double rate, const Worst& w)
    {
        std::printf ("  %-6s %6.1f kHz  worst %+6.3f dB at %7.0f Hz, %5.2f dB cut, band %7.1f ... %7.1f Hz  (%d responses, tail %.1e)\n",
                     what, rate / 1000.0, w.errorDb, w.hz, w.depthDb, w.band.low, w.band.high, w.cases, w.tail);
        std::printf ("         outside the band: %+6.3f dB at %7.0f Hz, %5.2f dB cut, band %7.1f ... %7.1f Hz; to 16 dB of cut %+6.3f dB; analog %+7.4f dB\n",
                     w.outside.db, w.outside.hz, w.outside.depthDb, w.outside.band.low, w.outside.band.high, w.outsideTo16Db.db, w.outsideAnalog.db);
    }

    void requireGate (const char* what, double rate, const Worst& w)
    {
        INFO (what << " at " << rate << " Hz: worst " << w.errorDb << " dB at " << w.hz << " Hz, " << w.depthDb << " dB cut, band "
                   << w.band.low << " ... " << w.band.high << " Hz, over " << w.cases << " responses");
        CHECK (w.cases > 0);
        CHECK (w.tail < 1.0e-12);
        CHECK (std::abs (w.errorDb) <= 0.5);

        // The collateral gate (0.1 dB a third of an octave past the edges) holds to 16 dB of cut at
        // every rate. Deeper, the analog prototype sits on 0.1 dB by design and the digital cut adds
        // up to 0.09 dB near 0.45 fs at 44.1 and 48 kHz: held to that here, the written gate in
        // "Split collateral at the deepest cuts near Nyquist" (split/NOTES.md, The edges).
        INFO ("outside the band " << w.outside.db << " dB at " << w.outside.hz << " Hz, " << w.outside.depthDb << " dB cut, band " << w.outside.band.low
                                  << " ... " << w.outside.band.high << " Hz; to 16 dB of cut " << w.outsideTo16Db.db << " dB; analog " << w.outsideAnalog.db << " dB");
        CHECK (std::abs (w.outsideTo16Db.db) <= 0.1 + 1.0e-3);     // the Harsh band's deepest, 12 dB, sits on 0.1 dB
        CHECK (std::abs (w.outsideAnalog.db) <= 0.1 + 1.0e-6);
        CHECK (std::abs (w.outside.db) <= (rate < 50000.0 ? 0.2 : 0.1 + 1.0e-3));
    }

    /** The chain's depth for hop values in dB: the quadratic B-spline of ReductionTrack. */
    std::vector<float> splineDepths (const std::vector<double>& hopDb)
    {
        std::vector<float> d (hopDb.size() * 32 + SplitFilter::interval);
        const auto depthOf = [&] (int h) { return 1.0 - std::pow (10.0, -hopDb[(size_t) std::max (h, 0)] / 20.0); };
        for (int h = 0; h < (int) hopDb.size(); ++h)
            for (int j = 0; j < 32; ++j)
            {
                const auto u = (j + 1) / 32.0, p0 = depthOf (h - 2), p1 = depthOf (h - 1), p2 = depthOf (h);
                d[(size_t) (h * 32 + j)] = (float) (0.5 * (1 - u) * (1 - u) * p0 + (0.5 + u * (1 - u)) * p1 + 0.5 * u * u * p2);
            }
        std::fill (d.end() - SplitFilter::interval, d.end(), d[d.size() - SplitFilter::interval - 1]);
        return d;
    }

    /**
        The largest spectral radius of the filter's sections frozen at their current coefficients: a
        TPT SVF's state matrix [[2 a1 − 1, −2 a2], [2 a2, 1 − 2 a3]], a one-pole's 1 − 2 a1.
    */
    double frozenRadius (const SplitFilter& filter, const splitDesign::Prototype& p, SplitKind kind)
    {
        const auto& c = filter.current();
        const auto perShelf = p.pairs + p.reals, sections = perShelf * (kind == SplitKind::bell ? 2 : 1);
        auto worst = 0.0;
        for (int k = 0; k < sections; ++k)
        {
            const auto a1 = c[(size_t) (5 * k)], a2 = c[(size_t) (5 * k + 1)], a3 = c[(size_t) (5 * k + 2)];
            if (k % perShelf < p.pairs)
            {
                const auto trace = 2.0 * a1 - 2.0 * a3, det = (2.0 * a1 - 1.0) * (1.0 - 2.0 * a3) + 4.0 * a2 * a2;
                const auto root = std::sqrt (Complex (trace * trace - 4.0 * det));
                worst = std::max ({ worst, std::abs ((trace + root) / 2.0), std::abs ((trace - root) / 2.0) });
            }
            else
            {
                worst = std::max (worst, std::abs (1.0 - 2.0 * a1));
            }
        }
        return worst;
    }


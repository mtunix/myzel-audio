"""
The files a netlist reads (itself, then its .include chain and its '*@ depends' files depth
first) and their digest, which a generated header carries. A header derived otherwise names its
sources on a line of its own (`// Sources in <folder> (sha256 <digest>): <file> ...`). Standard
library only, so the staleness check runs wherever python3 does (`python3 sources.py`;
validate.py runs it too).
"""

import hashlib
import os
import re
import sys

sys.dont_write_bytecode = True     # no __pycache__ in the source tree

HEADER_RE = re.compile(r"^// GENERATED by plugins/viridian/tools/netlist from (\S+) \(sha256 ([0-9a-f]{16})")
SOURCES_RE = re.compile(r"^// Sources in (\S+) \(sha256 ([0-9a-f]{16})\): (.+)$")


def files(path, seen=None):
    """The netlist and every file it includes, in the order the reader expands them."""
    seen = seen or set()
    path = os.path.abspath(path)
    if path in seen:
        raise ValueError(f"recursive .include of {path}")
    seen = seen | {path}
    out = [path]
    in_control = False
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            low = line.strip().lower()
            if low.startswith(".control"):
                in_control = True
            elif low.startswith(".endc"):
                in_control = False
            elif not in_control and (low.startswith(".include") or low.startswith(".inc ")):
                target = line.strip().split(None, 1)[1].strip().strip('"')
                out += files(os.path.join(os.path.dirname(path), target), seen)
            elif low.startswith("*@") and low[2:].split()[:1] == ["depends"]:
                # Parts copied from another netlist: a change there makes this one's header stale.
                target = line.strip()[2:].split()[1]
                out += files(os.path.join(os.path.dirname(path), target), seen)
    return out


def digest_of(paths):
    """sha256 of the bytes of the files, in order."""
    h = hashlib.sha256()
    for f in paths:
        with open(f, "rb") as fh:
            h.update(fh.read())
    return h.hexdigest()[:16]


def digest(path):
    """The digest of every file the netlist reads (a netlist without includes: its own)."""
    return digest_of(files(path))


def stale_headers(root, repo_root):
    """(header, netlist, why) for every generated header under `root` whose netlist changed."""
    out = []
    for base, dirs, names in os.walk(root):
        dirs[:] = sorted(d for d in dirs if not d.startswith(".") and not d.startswith("build"))
        for name in sorted(names):
            if not name.endswith(".h"):
                continue
            header = os.path.join(base, name)
            with open(header, encoding="utf-8", errors="replace") as fh:
                head = [fh.readline().rstrip("\n") for _ in range(6)]
            match = next((m for m in map(HEADER_RE.match, head) if m), None)
            if match:
                netlist = os.path.join(repo_root, match.group(1))
                if not os.path.exists(netlist):
                    out.append((header, netlist, "its netlist is missing"))
                elif digest(netlist) != match.group(2):
                    out.append((header, netlist, f"stamped {match.group(2)}, the netlist and its includes now {digest(netlist)}"))
                continue
            match = next((m for m in map(SOURCES_RE.match, head) if m), None)
            if match:
                folder = os.path.join(repo_root, match.group(1))
                paths = [os.path.join(folder, f) for f in match.group(3).split()]
                missing = [p for p in paths if not os.path.exists(p)]
                if missing:
                    out.append((header, missing[0], "a source is missing"))
                elif digest_of(paths) != match.group(2):
                    out.append((header, folder, f"stamped {match.group(2)}, its sources now {digest_of(paths)}"))
    return out


def main():
    """Exit 1 when a generated header under plugins/viridian is older than its netlist."""
    here = os.path.dirname(os.path.abspath(__file__))
    plugin = os.path.normpath(os.path.join(here, "..", ".."))
    stale = stale_headers(plugin, os.path.normpath(os.path.join(plugin, "..", "..")))
    for header, netlist, why in stale:
        print(f"{os.path.relpath(header, plugin)}: out of date with {os.path.relpath(netlist, plugin)} ({why}); "
              "regenerate it with the command in its first lines")
    if not stale:
        print("every generated header matches its netlist and includes, or its named sources")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())

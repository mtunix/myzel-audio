#!/usr/bin/env python3
"""Writes the simple lower-case mapping that seed words are folded with (SeedCode.cpp).

The mapping is Unicode 15.0's simple lowercase (UnicodeData.txt field 13), compressed into runs
of code points that share one offset: a run covers every code point, or every second one. It is
part of the frozen word hash (a word must give the same seed in every version), so the script
refuses to run on a Python whose Unicode database is not 15.0: never regenerate it with another
version.

Usage, from the repository root:
    python3 plugins/inkcap/tools/unicode/lowercase.py plugins/inkcap/src/dsp/common/generated/LowerCaseTable.h
"""

import sys
import unicodedata

UNICODE_VERSION = "15.0.0"


def simple_lowercase():
    mapping = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        lower = chr(cp).lower()
        if cp == 0x0130:
            # Python applies SpecialCasing (U+0069 U+0307); the simple mapping is U+0069.
            mapping[cp] = 0x0069
        elif len(lower) == 1 and ord(lower) != cp:
            mapping[cp] = ord(lower)
        elif len(lower) > 1:
            raise SystemExit(f"unexpected multi-character lower case at U+{cp:04X}")
    return mapping


def runs(mapping):
    cps = sorted(mapping)
    out = []
    i = 0
    while i < len(cps):
        first = cps[i]
        delta = mapping[first] - first
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1 and mapping[cps[j + 1]] - cps[j + 1] == delta:
            j += 1
        k = i
        while k + 1 < len(cps) and cps[k + 1] == cps[k] + 2 and mapping[cps[k + 1]] - cps[k + 1] == delta:
            k += 1
        if j >= k:
            out.append((first, cps[j], delta, 1))
            i = j + 1
        else:
            out.append((first, cps[k], delta, 2))
            i = k + 1
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(f"this Python has Unicode {unicodedata.unidata_version}; the frozen table is {UNICODE_VERSION}")

    mapping = simple_lowercase()
    table = runs(mapping)

    lines = [
        "#pragma once",
        "",
        "// GENERATED by plugins/inkcap/tools/unicode/lowercase.py: Unicode " + UNICODE_VERSION + " simple lowercase,",
        f"// {len(mapping)} code points in {len(table)} runs. Do not edit by hand. Regenerate from the repository root with:",
        "//   python3 plugins/inkcap/tools/unicode/lowercase.py plugins/inkcap/src/dsp/common/generated/LowerCaseTable.h",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace inkcap::dsp::seedcode::generated",
        "{",
        "",
        "/** Code points first .. last (every one, or every second one: step) map to themselves plus offset. */",
        "struct LowerCaseRun",
        "{",
        "    char32_t first, last;",
        "    int32_t offset;",
        "    int32_t step;",
        "};",
        "",
        f"inline constexpr std::array<LowerCaseRun, {len(table)}> lowerCaseRuns {{ {{",
    ]
    for first, last, delta, step in table:
        lines.append(f"    {{ 0x{first:05X}, 0x{last:05X}, {delta}, {step} }},")
    lines += [
        "} };",
        "",
        f"inline constexpr int lowerCaseMappings = {len(mapping)};",
        "",
        "} // namespace inkcap::dsp::seedcode::generated",
        "",
    ]
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()

"""The Console's gain and Q laws, tabulated from the netlists (../NOTES.md, "Control laws").

    python3 laws.py           writes ../ConsoleLaws.h (checked in, never edited by hand)
    python3 laws.py --check   fails when ../ConsoleLaws.h differs from a fresh run

A knob's read-out is the circuit's own value at the band's calibration point: the gain law is the
inverse of G_cal (wiper), the band's deviation at full boost or cut there (highest Q for the mids,
bell for HF and LF); the Q law the inverse of Q_cal (gang a), the -3 dB-from-peak Q at full boost.
Both come from check.py's nodal solver (exact nullor op-amps), sampled densely and inverted with a
monotone cubic, then stored uniform in dB (gain) and in log Q.
Needs numpy and scipy.
"""

import hashlib
import math
import os
import sys
from concurrent.futures import ProcessPoolExecutor

import numpy as np
from scipy.interpolate import PchipInterpolator

sys.dont_write_bytecode = True
import check  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "ConsoleLaws.h"))
DENSE = 241             # wiper positions sampled per half (gain) or per travel (Q)
POINTS = 129            # stored per half-table


def spaced(a, b, n):
    """n points from a to b, denser towards both ends (where the laws are steep)."""
    u = np.linspace(0.0, 1.0, n)
    return a + (b - a) * 0.5 * (1.0 - np.cos(math.pi * u))


def gain_point(args):
    fam, band, g = args
    return 0.0 if g == 0.5 else check.cal_peak(fam, band, g)[1]


def q_point(args):
    fam, band, q = args
    return check.cal_q(fam, band, q)


def invert(xs, ys, targets):
    """x (y) at the targets from samples of a monotone y (x)."""
    order = np.argsort(ys)
    return PchipInterpolator(np.asarray(ys)[order], np.asarray(xs)[order])(targets)


def tables(pool):
    out = {}
    for fam in check.FAMILIES:
        for band in check.BANDS:
            cut, boost = spaced(0.0, 0.5, DENSE), spaced(0.5, 1.0, DENSE)
            g_cut = list(pool.map(gain_point, [(fam, band, g) for g in cut]))
            g_boost = list(pool.map(gain_point, [(fam, band, g) for g in boost]))
            cut_db = np.linspace(g_cut[0], 0.0, POINTS)
            boost_db = np.linspace(0.0, g_boost[-1], POINTS)
            wiper_cut = invert(cut, g_cut, cut_db)
            wiper_boost = invert(boost, g_boost, boost_db)
            wiper_cut[-1] = wiper_boost[0] = 0.5          # G = 0 is the centre tap, exactly
            wiper_cut[0], wiper_boost[-1] = 0.0, 1.0      # and the ends are the travel's ends (a short)
            entry = dict(cut=(cut_db[0], wiper_cut), boost=(boost_db[-1], wiper_boost))
            if band in check.MIDS:
                qs = spaced(0.0, 1.0, DENSE)
                q_of = np.array(list(pool.map(q_point, [(fam, band, q) for q in qs])))
                if np.any(np.diff(q_of) <= 0):
                    raise RuntimeError(f"{fam} {band}: Q law not monotonic")
                logq = np.linspace(math.log(q_of[0]), math.log(q_of[-1]), POINTS)
                gang = invert(qs, np.log(q_of), logq)
                gang[0], gang[-1] = 0.0, 1.0
                entry["q"] = (q_of[0], q_of[-1], gang)
            out[(fam, band)] = entry
            print(f"{fam} {band}: gain {g_cut[0]:+.4f} ... {g_boost[-1]:+.4f} dB"
                  + (f", Q {entry['q'][0]:.4f} ... {entry['q'][1]:.4f}" if "q" in entry else ""), file=sys.stderr)
    return out


def numbers(values):
    text = [repr(float(v)) for v in values]
    rows = [", ".join(text[i:i + 6]) for i in range(0, len(text), 6)]
    return ",\n            ".join(rows)


SOURCES = ("check.py", "laws.py", "early_front.cir", "early_back.cir", "later_front.cir", "later_back.cir")


def header(t):
    sources = b"".join(open(os.path.join(HERE, f), "rb").read() for f in SOURCES)
    digest = hashlib.sha256(sources).hexdigest()[:16]
    w = []
    w.append("#pragma once")
    w.append("")
    w.append("// GENERATED by plugins/viridian/src/dsp/models/console/netlist/laws.py from the Console netlists.")
    w.append("// Do not edit by hand. Regenerate from the repository root with:")
    w.append("//   python3 plugins/viridian/src/dsp/models/console/netlist/laws.py")
    # tools/netlist/sources.py checks this stamp (ctest), without numpy or scipy.
    w.append(f"// Sources in plugins/viridian/src/dsp/models/console/netlist (sha256 {digest}): {' '.join(SOURCES)}")
    w.append("")
    w.append("#include <array>")
    w.append("")
    w.append("namespace viridian::dsp::console")
    w.append("{")
    w.append("")
    w.append(f"inline constexpr int lawPoints = {POINTS};")
    w.append("")
    w.append("/** y at x = x0 + k (x1 - x0) / (lawPoints - 1), k = 0 ... lawPoints - 1. */")
    w.append("struct LawTable")
    w.append("{")
    w.append("    double x0, x1;")
    w.append("    std::array<double, lawPoints> y;")
    w.append("};")
    w.append("")
    w.append("/**")
    w.append("    One band's laws at its calibration point: the boost/cut wiper for a deviation in dB (cut")
    w.append("    and boost halves, both ending at 0 dB = the centre tap), and for the mids the Q pot's gang-a")
    w.append("    wiper for log Q.")
    w.append("*/")
    w.append("struct BandLaws")
    w.append("{")
    w.append("    LawTable cut, boost;")
    w.append("    bool hasQ;")
    w.append("    LawTable q;          // x in ln Q")
    w.append("};")
    w.append("")
    for fam in check.FAMILIES:
        w.append(f"inline constexpr std::array<BandLaws, 4> {fam}Laws {{ {{   // hf, hmf, lmf, lf")
        for band in check.BANDS:
            e = t[(fam, band)]
            lo, cut = e["cut"]
            hi, boost = e["boost"]
            w.append(f"    {{   // {band}")
            w.append(f"        {{ {lo!r}, 0.0, {{ {{")
            w.append(f"            {numbers(cut)} }} }} }},")
            w.append(f"        {{ 0.0, {hi!r}, {{ {{")
            w.append(f"            {numbers(boost)} }} }} }},")
            if "q" in e:
                qlo, qhi, gang = e["q"]
                w.append("        true,")
                w.append(f"        {{ {math.log(qlo)!r}, {math.log(qhi)!r}, {{ {{")
                w.append(f"            {numbers(gang)} }} }} }},")
            else:
                w.append("        false,")
                w.append("        { 0.0, 0.0, {} },")
            w.append("    },")
        w.append("} };")
        w.append("")
    w.append("} // namespace viridian::dsp::console")
    w.append("")
    return "\n".join(w)


def main():
    with ProcessPoolExecutor() as pool:
        text = header(tables(pool))
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                sys.exit(f"{OUT} is out of date: run laws.py")
        print("ConsoleLaws.h is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

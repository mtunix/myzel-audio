#pragma once

#include "plugin/Parameters.h"

#include <algorithm>
#include <array>
#include <cmath>

namespace umber::dsp
{

/**
    Static (non-adaptive) output compensation. A fixed curve per model keeps Auto gain free of
    pumping and fully deterministic.

    compensationDb (model, driveDb, bias) returns the gain (dB) applied to the wet signal so that
    a typical programme (-18 dBFS RMS) leaves at roughly the same loudness it came in with.

    The curves are calibrated per model, Emphasis and Bias setting (emphasisPoints x biasPoints
    rows from -1 to +1, interpolated linearly in drive, bias and emphasis), generated by the
    UmberCalibrate tool into AutoGainTables.h. Emphasis does need its own dimension: at high
    drive the circuit compresses the emphasised band, so the de-emphasised result is quieter or
    louder than the flat setting (up to 5 dB, UmberCalibrate --report).
*/
struct AutoGain
{
    static constexpr float minDriveDb = -6.0f;
    static constexpr float maxDriveDb = 56.0f; // Drive 10 + Slam
    static constexpr int tableSize = 32;
    static constexpr int biasPoints = 5;
    static constexpr int emphasisPoints = 5;

    using Table = std::array<float, tableSize>;
    using BiasTables = std::array<Table, biasPoints>;
    using ModelTables = std::array<BiasTables, emphasisPoints>;

    static constexpr float biasAt (int index) noexcept     { return -1.0f + 2.0f * (float) index / (float) (biasPoints - 1); }
    static constexpr float emphasisAt (int index) noexcept { return -1.0f + 2.0f * (float) index / (float) (emphasisPoints - 1); }

    static float compensationDb (Model model, float driveDb, float bias = 0.0f, float emphasis = 0.0f) noexcept;

    /** Generic estimate: soft-knee compression of a -18 dBFS RMS programme. */
    static float estimateDb (float driveDb) noexcept
    {
        constexpr float programmeDb = -18.0f;
        constexpr float kneeDb = -14.0f;
        constexpr float width = 4.0f;
        constexpr float slopeAbove = 0.25f;

        const float in = programmeDb + driveDb;
        const float over = width * std::log1p (std::exp ((in - kneeDb) / width));
        const float out = in - over * (1.0f - slopeAbove);
        return programmeDb - out;
    }

    static float tableLookup (const Table& table, float driveDb) noexcept
    {
        const float pos = (std::clamp (driveDb, minDriveDb, maxDriveDb) - minDriveDb)
                          / (maxDriveDb - minDriveDb) * (tableSize - 1);
        const int i = std::min ((int) pos, tableSize - 2);
        const float frac = pos - (float) i;
        return table[(size_t) i] + frac * (table[(size_t) i + 1] - table[(size_t) i]);
    }

    static float tableLookup (const BiasTables& tables, float driveDb, float bias) noexcept
    {
        const float pos = (std::clamp (bias, -1.0f, 1.0f) + 1.0f) * 0.5f * (biasPoints - 1);
        const int i = std::min ((int) pos, biasPoints - 2);
        const float frac = pos - (float) i;
        const auto a = tableLookup (tables[(size_t) i], driveDb);

        if (frac == 0.0f)
            return a;

        return a + frac * (tableLookup (tables[(size_t) i + 1], driveDb) - a);
    }

    static float tableLookup (const ModelTables& tables, float driveDb, float bias, float emphasis) noexcept
    {
        const float pos = (std::clamp (emphasis, -1.0f, 1.0f) + 1.0f) * 0.5f * (emphasisPoints - 1);
        const int i = std::min ((int) pos, emphasisPoints - 2);
        const float frac = pos - (float) i;
        const auto a = tableLookup (tables[(size_t) i], driveDb, bias);

        if (frac == 0.0f)
            return a;

        return a + frac * (tableLookup (tables[(size_t) i + 1], driveDb, bias) - a);
    }
};

} // namespace umber::dsp

"""ngspice AC responses of the Console card at representative settings, for ConsoleTests.cpp.

    python3 plugins/viridian/tests/models/console/reference/make_reference.py

Writes ConsoleReference.h next to this file (checked in, never edited by hand). Each setting is
one card's pots as the netlists name them; the response is front times back (the split is exact,
../../../../src/dsp/models/console/NOTES.md), each from its own ngspice AC sweep.
Needs ngspice, numpy and scipy.
"""

import os
import random
import sys

import numpy as np

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
NETLISTS = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "src", "dsp", "models", "console", "netlist"))
sys.path.insert(0, NETLISTS)
import check  # noqa: E402

FRONT = ("hpf_in", "hpf_freq", "lpf_in", "lpf_freq", "hf_gain", "hf_freq", "hf_bell", "hmf_gain", "hmf_freq", "hmf_q")
BACK = ("lmf_gain", "lmf_freq", "lmf_q", "lf_gain", "lf_freq", "lf_bell")
ORDER = FRONT + BACK
FLAT = dict(hpf_in=0, hpf_freq=1.0, lpf_in=0, lpf_freq=0.0, hf_gain=0.5, hf_freq=0.5, hf_bell=1,
            hmf_gain=0.5, hmf_freq=0.5, hmf_q=0.5, lmf_gain=0.5, lmf_freq=0.5, lmf_q=0.5,
            lf_gain=0.5, lf_freq=0.5, lf_bell=1)
POINTS_PER_DECADE = 40


def settings():
    """(name, pots) per card: flat, every band at its extremes, the filters, and seeded mixes."""
    named = [
        ("flat", {}),
        ("HF bell boost, top", dict(hf_gain=1.0, hf_freq=0.0)),
        ("HF bell cut, middle", dict(hf_gain=0.0, hf_freq=0.5)),
        ("HF shelf boost, bottom", dict(hf_gain=1.0, hf_freq=1.0, hf_bell=0)),
        ("HF shelf cut, top", dict(hf_gain=0.1, hf_freq=0.0, hf_bell=0)),
        ("HMF boost, highest Q, middle", dict(hmf_gain=1.0, hmf_freq=0.5, hmf_q=1.0)),
        ("HMF cut, lowest Q, top", dict(hmf_gain=0.0, hmf_freq=0.0, hmf_q=0.0)),
        ("HMF boost, highest Q, top", dict(hmf_gain=1.0, hmf_freq=0.0, hmf_q=1.0)),
        ("LMF boost, highest Q, bottom", dict(lmf_gain=1.0, lmf_freq=1.0, lmf_q=1.0)),
        ("LMF cut, middle Q", dict(lmf_gain=0.2, lmf_freq=0.3, lmf_q=0.5)),
        ("LF bell boost, bottom", dict(lf_gain=1.0, lf_freq=1.0)),
        ("LF shelf cut, top", dict(lf_gain=0.0, lf_freq=0.0, lf_bell=0)),
        ("LF shelf boost, middle", dict(lf_gain=0.9, lf_freq=0.5, lf_bell=0)),
        ("high-pass, lowest", dict(hpf_in=1, hpf_freq=1.0)),
        ("high-pass, middle", dict(hpf_in=1, hpf_freq=0.5)),
        ("high-pass, highest", dict(hpf_in=1, hpf_freq=0.0)),
        ("low-pass, 22 kHz", dict(lpf_in=1, lpf_freq=0.09)),
        ("low-pass, lowest", dict(lpf_in=1, lpf_freq=1.0)),
        ("both filters, all bands boosted", dict(hpf_in=1, hpf_freq=0.6, lpf_in=1, lpf_freq=0.4, hf_gain=1.0,
                                                  hmf_gain=1.0, hmf_q=1.0, lmf_gain=1.0, lmf_q=1.0, lf_gain=1.0)),
        ("all bands cut, shelves", dict(hf_gain=0.0, hf_bell=0, hmf_gain=0.0, lmf_gain=0.0, lf_gain=0.0, lf_bell=0)),
    ]
    rng = random.Random(42)
    for k in range(8):
        pots = {p: round(rng.random(), 4) for p in ORDER if p not in ("hpf_in", "lpf_in", "hf_bell", "lf_bell")}
        pots.update(hpf_in=rng.randint(0, 1), lpf_in=rng.randint(0, 1), hf_bell=rng.randint(0, 1), lf_bell=rng.randint(0, 1))
        named.append((f"random {k + 1}", pots))
    for card in ("early", "later"):
        for name, pots in named:
            yield card, name, {**FLAT, **pots}


def response(card, pots):
    front = {k: pots[k] for k in FRONT}
    back = {k: pots[k] for k in BACK}
    f, hf = check.ac(f"{card}_front.cir", front, 10.0, 24000.0, POINTS_PER_DECADE)
    _, hb = check.ac(f"{card}_back.cir", back, 10.0, 24000.0, POINTS_PER_DECADE)
    return f, hf[:, 0] * hb[:, 0]


def main():
    rows, freqs = [], None
    for card, name, pots in settings():
        f, h = response(card, pots)
        freqs = f if freqs is None else freqs
        if len(f) != len(freqs) or np.max(np.abs(f / freqs - 1)) > 1e-12:
            raise RuntimeError("ngspice frequency grids differ")
        rows.append((card, name, pots, h))
    w = []
    w.append("#pragma once")
    w.append("")
    w.append("// GENERATED by plugins/viridian/tests/models/console/reference/make_reference.py: ngspice 42 AC")
    w.append("// responses of the Console netlists. Do not edit by hand. Regenerate from the repository root with:")
    w.append("//   python3 plugins/viridian/tests/models/console/reference/make_reference.py")
    w.append("")
    w.append("#include <array>")
    w.append("")
    w.append("namespace viridian::testing::console")
    w.append("{")
    w.append("")
    w.append(f"inline constexpr int referenceFrequencies = {len(freqs)};")
    w.append(f"inline constexpr std::array<double, {len(freqs)}> referenceHz {{ {{")
    for i in range(0, len(freqs), 6):
        w.append("    " + ", ".join(repr(float(x)) for x in freqs[i:i + 6]) + ",")
    w.append("} };")
    w.append("")
    w.append("struct ReferenceSetting")
    w.append("{")
    w.append("    const char* name;")
    w.append("    bool later;")
    w.append(f"    std::array<double, {len(ORDER)}> pots;   // {', '.join(ORDER)}")
    w.append("    std::array<double, referenceFrequencies> re, im;")
    w.append("};")
    w.append("")
    w.append(f"inline constexpr std::array<ReferenceSetting, {len(rows)}> referenceSettings {{ {{")
    for card, name, pots, h in rows:
        w.append(f'    {{ "{card}: {name}", {"true" if card == "later" else "false"},')
        w.append("      { " + ", ".join(repr(float(pots[k])) for k in ORDER) + " },")
        for part in (h.real, h.imag):
            w.append("      { " + ", ".join(repr(float(x)) for x in part) + " },")
        w.append("    },")
    w.append("} };")
    w.append("")
    w.append("} // namespace viridian::testing::console")
    w.append("")
    out = os.path.join(HERE, "ConsoleReference.h")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(w))
    print(f"wrote {out}: {len(rows)} settings x {len(freqs)} frequencies")


if __name__ == "__main__":
    main()
